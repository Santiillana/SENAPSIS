import { test, expect } from "./navigation.js";

test("Administrar crea y desactiva competencia, horario, instructor y comunicado",async({page})=>{
  let savedPayload=null;
  await page.route("**/api/v1/admin/session",route=>route.fulfill({json:{authenticated:true,email:"moderator@example.edu"}}));
  await page.route("**/api/v1/admin/draft",async route=>{
    if(route.request().method()==="GET")return route.fulfill({json:{baseVersion:0,payload:null}});
    savedPayload=route.request().postDataJSON();return route.fulfill({json:{saved:true,baseVersion:0,updatedAt:"2026-11-19T18:05:00Z"}});
  });
  await page.route("**/api/v1/state",route=>route.fulfill({json:{version:0,updatedAt:null,payload:null}}));
  await page.route("**/api/v1/admin/history",route=>route.fulfill({json:{publications:[],audit:[]}}));
  await page.setViewportSize({width:390,height:844});await page.goto("/administrar.html");
  await page.locator('[data-admin-tab="management"]').click();
  await page.locator('[data-manage-form="competencia"] [name="nombre"]').fill("Laboratorio de prueba");
  await page.locator('[data-manage-form="competencia"] [name="codigo"]').fill("LAB-01");
  await page.locator('[data-manage-form="competencia"] [name="color"]').fill("#345678");
  await page.locator('[data-manage-form="competencia"] [type="submit"]').click();
  await expect(page.locator("#admin-feedback")).toContainText("Borrador guardado",{timeout:5000});
  const competenceId=savedPayload.competencias.at(-1).id;
  expect(savedPayload.competencias.at(-1).color).toBe("#345678");
  await page.locator('[data-admin-tab="daily"]').click();
  await expect(page.locator('#admin-daily-form [name="competencia"] option').filter({hasText:"Laboratorio de prueba"})).toHaveCount(1);
  await page.locator('[data-admin-tab="management"]').click();
  await page.locator('[data-manage-form="instructor"] [name="nombre"]').fill("Instructor nuevo");
  await page.locator('[data-manage-form="instructor"] [name="contactoPublico"]').check();
  await page.locator('[data-manage-form="instructor"] [name="correo"]').fill("instructor@example.edu");
  await page.locator('[data-manage-form="instructor"] [type="submit"]').click();
  await expect(page.locator("#admin-feedback")).toContainText("Borrador guardado",{timeout:5000});
  const instructorId=savedPayload.instructores.at(-1).id;
  await page.locator('[data-manage-form="horario"] [name="dia"]').selectOption("4");
  await page.locator('[data-manage-form="horario"] [name="competenciaId"]').selectOption(competenceId);
  await page.locator('[data-manage-form="horario"] [name="instructorId"]').selectOption(instructorId);
  await page.locator('[data-manage-form="horario"] [name="inicio"]').fill("17:00");
  await page.locator('[data-manage-form="horario"] [name="fin"]').fill("20:00");
  await page.locator('[data-manage-form="horario"] [type="submit"]').click();
  await expect(page.locator("#admin-feedback")).toContainText("Borrador guardado",{timeout:5000});
  await page.locator('[data-manage-form="comunicado"] [name="titulo"]').fill("Aviso de prueba");
  await page.locator('[data-manage-form="comunicado"] [name="texto"]').fill("La sesión inicia a las cinco.");
  await page.locator('[data-manage-form="comunicado"] [name="fecha"]').fill("2026-11-19");
  await page.locator('[data-manage-form="comunicado"] [name="fijado"]').check();
  await page.locator('[data-manage-form="comunicado"] [type="submit"]').click();
  await expect(page.locator("#admin-feedback")).toContainText("Borrador guardado",{timeout:5000});
  expect(savedPayload.horario.at(-1).competenciaId).toBe(competenceId);
  expect(savedPayload.horario.at(-1).instructorId).toBe(instructorId);
  expect(savedPayload.instructores.at(-1).contactoPublico).toBe(true);
  expect(savedPayload.comunicados.at(-1).fijado).toBe(true);
  await page.locator(`[data-manage-active][data-id="${competenceId}"]`).click();
  await expect(page.locator("#admin-feedback")).toContainText("Borrador guardado",{timeout:5000});
  expect(savedPayload.competencias.find(item=>item.id===competenceId).activa).toBe(false);
  await page.locator('[data-admin-tab="daily"]').click();
  await expect(page.locator('#admin-daily-form [name="competencia"] option').filter({hasText:"Laboratorio de prueba"})).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1);
});
